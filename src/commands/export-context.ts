import { readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { join, relative, resolve, dirname, basename } from 'node:path';
import fg from 'fast-glob';
import matter from 'gray-matter';
import pc from 'picocolors';
import {
  findProjectRoot,
  loadConfig,
  brandwikiDir,
  type BrandwikiConfig,
} from '../lib/config.js';

interface ExportContextOptions {
  out?: string;
  categories?: string;
  format?: string;
  maxChars?: string;
}

type ExportFormat = 'plain' | 'octogent';

interface Article {
  category: string;
  slug: string;
  title: string;
  status?: string;
  confidence?: string;
  updated?: string;
  sources?: string[];
  body: string;
  relPath: string;
}

const DEFAULT_MAX_CHARS = 400_000;

function slugFromFilename(file: string): string {
  return basename(file, '.md');
}

function anchorFor(article: Article): string {
  return `${article.category}--${article.slug}`;
}

function parseCategories(input: string | undefined): Set<string> | null {
  if (!input) return null;
  const ids = input
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);
  return ids.length > 0 ? new Set(ids) : null;
}

function loadArticles(
  wikiDir: string,
  categoryFilter: Set<string> | null
): Article[] {
  const files = fg.sync('**/*.md', { cwd: wikiDir, absolute: true, dot: false });
  const articles: Article[] = [];

  for (const abs of files) {
    if (basename(abs).toLowerCase() === 'readme.md') continue;
    const stat = statSync(abs);
    if (!stat.isFile()) continue;

    const rel = relative(wikiDir, abs).replaceAll('\\', '/');
    const parts = rel.split('/');
    if (parts.length < 2) continue;
    const category = parts[0];
    if (categoryFilter && !categoryFilter.has(category)) continue;

    const raw = readFileSync(abs, 'utf-8');
    const parsed = matter(raw);
    const data = parsed.data as Record<string, unknown>;

    const title =
      typeof data.title === 'string' && data.title.trim().length > 0
        ? data.title.trim()
        : slugFromFilename(abs);

    const sources = Array.isArray(data.sources)
      ? data.sources.filter((s): s is string => typeof s === 'string')
      : undefined;

    articles.push({
      category,
      slug: slugFromFilename(abs),
      title,
      status: typeof data.status === 'string' ? data.status : undefined,
      confidence: typeof data.confidence === 'string' ? data.confidence : undefined,
      updated: typeof data.updated === 'string' ? data.updated : undefined,
      sources,
      body: parsed.content.trim(),
      relPath: rel,
    });
  }

  articles.sort((a, b) => {
    if (a.category !== b.category) return a.category.localeCompare(b.category);
    return a.slug.localeCompare(b.slug);
  });

  return articles;
}

function groupByCategory(
  articles: Article[]
): Array<{ category: string; title: string; articles: Article[] }> {
  const byCat = new Map<string, Article[]>();
  for (const a of articles) {
    const list = byCat.get(a.category) ?? [];
    list.push(a);
    byCat.set(a.category, list);
  }
  return Array.from(byCat.entries()).map(([category, list]) => ({
    category,
    title: category,
    articles: list,
  }));
}

function renderBundle(
  articles: Article[],
  config: BrandwikiConfig,
  format: ExportFormat,
  wikiAbsPath: string,
  maxChars: number
): { body: string; included: number; truncated: Article[] } {
  const groups = groupByCategory(articles);
  const categoryTitles = new Map<string, string>();
  for (const c of config.categories) categoryTitles.set(c.id, c.title);

  const now = new Date().toISOString();
  const lines: string[] = [];

  if (format === 'octogent') {
    lines.push('<!--');
    lines.push('  Generated by `brandwiki export-context --format octogent`.');
    lines.push('  Do NOT edit by hand. Re-run the command to refresh.');
    lines.push(`  Source: ${wikiAbsPath}`);
    lines.push(`  Generated: ${now}`);
    lines.push('-->');
    lines.push('');
    lines.push(`# ${config.projectName} — Shared Project Knowledge`);
    lines.push('');
    lines.push(
      'This file is the compiled brand-wiki for this project, flattened into a single context document for an octogent tentacle. It is generated from `.brandwiki/wiki/` by `brandwiki export-context`. Agents reading this file should treat it as the current, authoritative project knowledge — not raw notes.'
    );
    lines.push('');
  } else {
    lines.push('---');
    lines.push(`source: brandwiki-engine`);
    lines.push(`project: ${config.projectName}`);
    lines.push(`generated: ${now}`);
    lines.push(`articles: ${articles.length}`);
    lines.push('---');
    lines.push('');
    lines.push(`# ${config.projectName} — Context Bundle`);
    lines.push('');
    lines.push(
      'Generated by `brandwiki export-context`. Re-run the command to refresh.'
    );
    lines.push('');
  }

  lines.push('## Table of contents');
  lines.push('');
  for (const group of groups) {
    const catTitle = categoryTitles.get(group.category) ?? group.category;
    lines.push(`- **${catTitle}** (\`${group.category}\`)`);
    for (const a of group.articles) {
      lines.push(`  - [${a.title}](#${anchorFor(a)})`);
    }
  }
  lines.push('');

  let charBudget = maxChars;
  let included = 0;
  const truncated: Article[] = [];

  for (const group of groups) {
    const catTitle = categoryTitles.get(group.category) ?? group.category;
    lines.push('---');
    lines.push('');
    lines.push(`## ${catTitle} \`${group.category}\``);
    lines.push('');

    for (const a of group.articles) {
      const meta: string[] = [];
      if (a.status) meta.push(`status: ${a.status}`);
      if (a.confidence) meta.push(`confidence: ${a.confidence}`);
      if (a.updated) meta.push(`updated: ${a.updated}`);

      const section: string[] = [];
      section.push(`<a id="${anchorFor(a)}"></a>`);
      section.push(`### ${a.title}`);
      if (meta.length > 0) section.push(`*${meta.join(' · ')}*`);
      section.push(`\`source: .brandwiki/wiki/${a.relPath}\``);
      section.push('');
      section.push(a.body);
      section.push('');

      const sectionText = section.join('\n');
      if (sectionText.length > charBudget) {
        truncated.push(a);
        continue;
      }

      lines.push(sectionText);
      charBudget -= sectionText.length;
      included++;
    }
  }

  if (truncated.length > 0) {
    lines.push('---');
    lines.push('');
    lines.push('## Truncated');
    lines.push('');
    lines.push(
      `The following articles exceeded the \`--max-chars\` budget and were omitted. Raise \`--max-chars\` or pass \`--categories\` to include them:`
    );
    for (const a of truncated) {
      lines.push(`- ${a.title} — \`.brandwiki/wiki/${a.relPath}\``);
    }
    lines.push('');
  }

  return { body: lines.join('\n'), included, truncated };
}

function resolveOutPath(
  outOption: string | undefined,
  format: ExportFormat,
  bwDir: string
): string {
  if (outOption) {
    const abs = resolve(process.cwd(), outOption);
    if (format === 'octogent') {
      const looksLikeFile = /\.(md|markdown)$/i.test(outOption);
      return looksLikeFile ? abs : join(abs, 'CONTEXT.md');
    }
    return abs;
  }

  if (format === 'octogent') {
    throw new Error(
      '`--format octogent` requires `--out <tentacle-dir>` (the octogent tentacle directory to write CONTEXT.md into).'
    );
  }

  return join(bwDir, 'outputs', 'context-bundle.md');
}

function parseFormat(value: string | undefined): ExportFormat {
  if (!value || value === 'plain') return 'plain';
  if (value === 'octogent') return 'octogent';
  throw new Error(`Unknown --format: ${value} (expected 'plain' or 'octogent')`);
}

function parseMaxChars(value: string | undefined): number {
  if (!value) return DEFAULT_MAX_CHARS;
  const n = Number.parseInt(value, 10);
  if (!Number.isFinite(n) || n <= 0) {
    throw new Error(`Invalid --max-chars: ${value}`);
  }
  return n;
}

export async function exportContextCommand(options: ExportContextOptions): Promise<void> {
  const root = findProjectRoot();
  const config = loadConfig(root);
  const bwDir = brandwikiDir(root);
  const wikiDir = join(bwDir, 'wiki');

  if (!existsSync(wikiDir)) {
    console.log(pc.yellow('No wiki/ directory found. Run `brandwiki compile` first.'));
    return;
  }

  const format = parseFormat(options.format);
  const maxChars = parseMaxChars(options.maxChars);
  const categoryFilter = parseCategories(options.categories);

  if (categoryFilter) {
    const unknown: string[] = [];
    const known = new Set(config.categories.map((c) => c.id));
    for (const id of categoryFilter) {
      if (!known.has(id)) unknown.push(id);
    }
    if (unknown.length > 0) {
      console.log(
        pc.yellow(`Unknown category id(s): ${unknown.join(', ')}`) +
          pc.dim(
            ` (known: ${config.categories.map((c) => c.id).join(', ')})`
          )
      );
    }
  }

  const articles = loadArticles(wikiDir, categoryFilter);
  if (articles.length === 0) {
    console.log(pc.yellow('No articles matched. Nothing to export.'));
    return;
  }

  const outPath = resolveOutPath(options.out, format, bwDir);
  const { body, included, truncated } = renderBundle(
    articles,
    config,
    format,
    wikiDir,
    maxChars
  );

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, body, 'utf-8');

  const displayPath = relative(process.cwd(), outPath).replaceAll('\\', '/') || outPath;
  console.log(
    pc.green(`✓ Exported ${included} article${included === 1 ? '' : 's'}`) +
      pc.dim(` → ${displayPath}`)
  );
  if (truncated.length > 0) {
    console.log(
      pc.yellow(
        `  ${truncated.length} article${truncated.length === 1 ? '' : 's'} skipped (over --max-chars=${maxChars})`
      )
    );
  }
  if (format === 'octogent') {
    console.log(
      pc.dim(
        `  Tip: point your tentacle at this file, or symlink CONTEXT.md to it. Re-run to refresh.`
      )
    );
  }
}
