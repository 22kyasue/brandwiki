import type { Fact } from './fact.js';
import { resolve } from './resolver.js';
import { assess } from './freshness.js';

export interface DigestOptions {
  /** The project's full ledger facts (resolution happens here). */
  facts: Fact[];
  /** Relevant behavior rules from MEMORY.md, composed in at build time. */
  memoryRules: string[];
  now?: Date;
  windowDays?: number;
  /** Optional set of fact ids known to be stale (from a Freshness pass over
   *  live sources). Pure callers can omit it. */
  staleIds?: Set<string>;
}

const STAMP = '<!-- GENERATED by brandwiki — do not edit. Regenerate from the Fact Ledger. -->';

/**
 * Build the per-session Digest (ADR 0002): the compact, "do not edit" brief
 * auto-injected into a session. Composed from the project's resolved durable
 * Facts, Pointer Facts (rendered as "go look here", never an inline copy of the
 * volatile value), inline freshness dates, surfaced unresolved conflicts, and
 * the relevant MEMORY.md behavior rules. Output is text; it is itself a Render
 * and is never authoritative.
 */
export function buildDigest(project: string, options: DigestOptions): string {
  const now = options.now ?? new Date();
  const staleIds = options.staleIds ?? new Set<string>();
  const { current, unresolvedConflicts } = resolve(options.facts, { windowDays: options.windowDays });

  const decisions = current.filter((f) => f.kind === 'copied');
  const pointers = current.filter((f) => f.kind === 'pointer');

  const lines: string[] = [
    STAMP,
    `# Digest — ${project}`,
    `_Generated ${iso(now)}. Every fact below is dated; distrust anything stale._`,
  ];

  lines.push('', '## Decisions & current state');
  if (decisions.length === 0) lines.push('_None captured yet._');
  for (const f of decisions) lines.push(`- ${f.body} ${meta(f, now, staleIds)}`);

  if (pointers.length > 0) {
    lines.push('', '## Where live truth lives');
    for (const f of pointers) {
      lines.push(`- **${f.subject}** — live truth lives at \`${f.body}\` ${meta(f, now, staleIds)}`);
    }
  }

  if (unresolvedConflicts.length > 0) {
    lines.push('', '## ⚠ Unresolved conflicts — you decide');
    for (const conflict of unresolvedConflicts) {
      lines.push(`- **${conflict.subject}**:`);
      for (const f of conflict.facts) lines.push(`  - ${f.body} ${meta(f, now, staleIds)}`);
    }
  }

  if (options.memoryRules.length > 0) {
    lines.push('', '## Working-style rules');
    for (const rule of options.memoryRules) lines.push(`- ${rule}`);
  }

  return lines.join('\n') + '\n';
}

function meta(fact: Fact, now: Date, staleIds: Set<string>): string {
  const { ageDays } = assess(fact, fact.sourceHash, now); // hash matches itself: age only
  const stale = staleIds.has(fact.id) ? ', STALE' : '';
  return `_(${fact.source} · ${fact.createdAt}, ${ageDays}d ago${stale})_`;
}

function iso(date: Date): string {
  return date.toISOString().slice(0, 10);
}
